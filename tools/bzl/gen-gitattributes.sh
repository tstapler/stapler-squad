#!/usr/bin/env bash
# Keep the BUILD.bazel review-collapse rules in .gitattributes in step with tools/bzl/hand-build-files.txt
# (Task 11.6a): hand-written BUILD files and the root BUILD.bazel must always render in a diff.
#   gen-gitattributes.sh          rewrite the generated block (run by `make gazelle`)
#   gen-gitattributes.sh --check  exit 1 if the block is out of date
set -eu
root=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
list="${HAND_BUILD_FILES:-$root/tools/bzl/hand-build-files.txt}"
attrs="${GITATTRIBUTES:-$root/.gitattributes}"
begin="# BEGIN generated by tools/bzl/gen-gitattributes.sh (from hand-build-files.txt)"
end="# END generated by tools/bzl/gen-gitattributes.sh"

block() {
  echo "$begin"
  echo "**/BUILD.bazel linguist-generated"
  echo "/BUILD.bazel -linguist-generated"
  sed 's/[[:space:]]*#.*$//' "$list" | awk 'NF' | LC_ALL=C sort -u | while read -r f; do
    [ "$f" = "BUILD.bazel" ] || echo "/$f -linguist-generated"
  done
  echo "$end"
}


blockfile=$(mktemp "${TMPDIR:-/tmp}/gitattrs.XXXXXX")
trap 'rm -f "$blockfile"' EXIT
block > "$blockfile"
if grep -qF "$begin" "$attrs"; then
  out=$(awk -v b="$begin" -v e="$end" -v f="$blockfile" '
    $0 == b { while ((getline l < f) > 0) print l; skip=1; next }
    skip { if ($0 == e) skip=0; next }
    { print }' "$attrs")
else
  # first run: replace the hand-written collapse line with the generated block
  out=$( { grep -vE '^\*\*/BUILD\.bazel linguist-generated$' "$attrs"; echo; cat "$blockfile"; } )
fi
if [ "${1:-}" = "--check" ]; then
  [ "$out" = "$(cat "$attrs")" ] || { echo ".gitattributes is out of date with hand-build-files.txt. Remedy: run 'bash tools/bzl/gen-gitattributes.sh' (make gazelle does)." >&2; exit 1; }
  exit 0
fi
printf '%s\n' "$out" > "$attrs"
