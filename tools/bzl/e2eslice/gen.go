const genHeader = "# Generated by `tools/bzl/e2eslice gen-build` from tests/e2e/slice-manifest.json. DO NOT EDIT.\n# gazelle:ignore\n"

// nearestPackage returns the Bazel package (repo-relative dir with a BUILD file) that owns file.
func nearestPackage(repoRoot, file string) string {
	d := path.Dir(file)
	for d != "." && d != "/" {
		for _, n := range []string{"BUILD.bazel", "BUILD"} {
			if st, err := os.Stat(filepath.Join(repoRoot, d, n)); err == nil && !st.IsDir() {
				return d
			}
		}
		d = path.Dir(d)
	}
	return ""
}

func fileLabel(repoRoot, file string) string {
	pkg := nearestPackage(repoRoot, file)
	return "//" + pkg + ":" + strings.TrimPrefix(strings.TrimPrefix(file, pkg), "/")
}

// goLabel maps an import path to Gazelle's go_library label (name = directory base). The root package is the
// binary seam and `server/web` is the embedded dist, so neither belongs in a slice (ADR-009 decision 1).
func goLabel(pkg string) (string, bool) {
	rel := strings.TrimPrefix(strings.TrimPrefix(pkg, modulePath), "/")
	if rel == "" || rel == "server/web" || !strings.HasPrefix(pkg, modulePath+"/") {
		return "", false
	}
	return "//" + rel, true
}

func quoteList(xs []string, indent string) string {
	if len(xs) == 0 {
		return "[]"
	}
	var b strings.Builder
	b.WriteString("[\n")
	for _, x := range xs {
		fmt.Fprintf(&b, "%s    %q,\n", indent, x)
	}
	b.WriteString(indent + "]")
	return b.String()
}

// genBuild renders tests/e2e/BUILD.bazel: one e2e_test per spec group over the managed specs, plus the
// global_inputs filegroup. quarantined specs make their target `no-cache`.
func genBuild(repoRoot string, m *Manifest, globalInputs []string, quarantined map[string]bool) string {
	byEntry := map[string]Entry{}
	var managed []string
	for _, e := range m.Specs {
		byEntry[e.Spec] = e
		managed = append(managed, e.Spec)
	}
	sort.Strings(managed)
	var b strings.Builder
	b.WriteString(genHeader)
	b.WriteString("\nload(\"//tools/bzl/e2e:e2e.bzl\", \"e2e_test\")\n\n")
	b.WriteString("filegroup(\n    name = \"global_inputs\",\n    srcs = glob(\n        " + quoteList(globalInputsForGlob(globalInputs), "        ") + ",\n        allow_empty = True,\n    ),\n    visibility = [\"//visibility:public\"],\n)\n")
	for _, g := range groupSpecs(managed) {
		goSet, webSet, nocache := map[string]bool{}, map[string]bool{}, false
		var specs []string
		for _, sp := range g.Specs {
			e := byEntry[sp]
			specs = append(specs, strings.TrimPrefix(sp, "tests/e2e/"))
			for _, p := range e.GoPkgs {
				if l, ok := goLabel(p); ok {
					goSet[l] = true
				}
			}
			for _, w := range e.WebFiles {
				webSet[fileLabel(repoRoot, w)] = true
			}
			nocache = nocache || quarantined[sp]
		}
		tags := "[]"
		if nocache {
			tags = `["no-cache"]`
		}
		fmt.Fprintf(&b, "\ne2e_test(\n    name = %q,\n    specs = %s,\n    go_pkgs = %s,\n    web_files = %s,\n    tags = %s,\n)\n",
			g.Name, quoteList(specs, "    "), quoteList(keys(goSet), "    "), quoteList(keys(webSet), "    "), tags)
	}
	return b.String()
}

func keys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// globalInputsForGlob keeps only entries under tests/e2e (the package's own files); the rest are
// referenced from the manifest-wide check and the affected-e2e selector, which see repo-relative paths.
func globalInputsForGlob(globs []string) []string {
	var out []string
	for _, g := range globs {
		if rest, ok := strings.CutPrefix(g, "tests/e2e/"); ok {
			out = append(out, rest)
		}
	}
	return out
}

var binaryDep = regexp.MustCompile(`^//(:stapler-squad|server/web:(dist|embed.*|staging.*))$`)

// checkNoBinaryDep fails when the e2e deps closure reaches the server binary or the embedded dist.
func checkNoBinaryDep(queryOutput string) []string {
	var bad []string
	for _, l := range strings.Split(queryOutput, "\n") {
		if l = strings.TrimSpace(l); binaryDep.MatchString(l) {
			bad = append(bad, l)
		}
	}
	return bad
}

// checkGlobalInputs verifies every glob in the list matches at least one file under repoRoot.
func checkGlobalInputs(repoRoot string, globs []string) []string {
	var files []string
	_ = filepath.WalkDir(repoRoot, func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if d.IsDir() && (d.Name() == "node_modules" || d.Name() == ".git" || d.Name() == "bazel-out") {
			return filepath.SkipDir
		}
		if !d.IsDir() {
			if rel, e := filepath.Rel(repoRoot, p); e == nil {
				files = append(files, filepath.ToSlash(rel))
			}
		}
		return nil
	})
	var missing []string
	for _, g := range globs {
		re, ok := globToRegexp(g), false
		for _, f := range files {
			if re.MatchString(f) {
				ok = true
				break
			}
		}
		if !ok {
			missing = append(missing, g)
		}
	}
	return missing
}

// Shard is one runner's slice of the selected targets.
type Shard struct {
	Shard   int      `json:"shard"`
	Targets []string `json:"targets"`
	Seconds float64  `json:"seconds"`
}

// planShards is longest-processing-time-first over per-target durations; unknown targets get the median.
func planShards(targets []string, durations map[string]float64, n int) []Shard {
	var known []float64
	for _, t := range targets {
		if d, ok := durations[t]; ok {
			known = append(known, d)
		}
	}
	sort.Float64s(known)
	med := median(known)
	type td struct {
		t string
		d float64
	}
	var work []td
	for _, t := range targets {
		d, ok := durations[t]
		if !ok {
			d = med
		}
		work = append(work, td{t, d})
	}
	sort.Slice(work, func(i, j int) bool {
		if work[i].d != work[j].d {
			return work[i].d > work[j].d
		}
		return work[i].t < work[j].t
	})
	shards := make([]Shard, n)
	for i := range shards {
		shards[i].Shard = i + 1
	}
	for _, w := range work {
		min := 0
		for i := range shards {
			if shards[i].Seconds < shards[min].Seconds {
				min = i
			}
		}
		shards[min].Targets = append(shards[min].Targets, w.t)
		shards[min].Seconds += w.d
	}
	return shards
}
